import sys, json
from playwright.sync_api import sync_playwright
PATH, OUT = sys.argv[1], sys.argv[2]
exec(open('seed_u4.py').read())
results = []
def rec(name, ok, detail=''):
    results.append((name, 'PASS' if ok else 'FAIL', str(detail)[:220])); print('PASS' if ok else 'FAIL', name, str(detail)[:220])
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, accept_downloads=True)
    page = ctx.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append('console:' + m.text) if m.type == 'error' else None)
    page.goto('file://' + PATH); page.wait_for_selector('.sj-dash', timeout=15000)
    t = page.inner_text('#mainView')
    rec('fresh: glass bento dashboard renders', page.locator('.gx .gx-card').count() >= 12)
    rec('fresh: 5 prompt widgets present (streak, goal, trend, revision, pomodoro)', all(page.locator(s).count() == 1 for s in ['.gx-streak', '.gx-goal', '.gx-trend', '.gx-rev', '.gx-pomo']))
    rec('fresh: honest empty states (no goal, no tests)', 'No goal set' in t and 'No tests yet' in t)
    rec('fresh: no backup nag without any history', page.locator('.gx-backup').count() == 0)
    rec('mesh/glass active only on Home', page.evaluate("document.body.classList.contains('sj-home-active')"))
    page.evaluate("navigate('subjects')")
    rec('glass background removed on other pages', not page.evaluate("document.body.classList.contains('sj-home-active')"))
    page.evaluate("navigate('home')")
    # Goal + exam date
    page.locator('.gx-goal .gx-btn').click()
    page.fill('#gxGoal', '20'); page.fill('#gxExamDate', page.evaluate("sjAddDays(sjLocalDay(),30)"))
    page.locator('#modalSheetBody .btn-nav.primary').click()
    rec('goal saved; ring shows 0 / 20', '0 / 20' in page.inner_text('.gx-goal'))
    rec('exam countdown shows 30 days', '30 days to exam' in page.inner_text('.gx-hero'))
    page.evaluate("(()=>{const m=getWorkspaceModule('maths-percentage-class-test');const qs=m.groups.flatMap(g=>g.questions);[0,1,2].forEach(i=>onPracticeSelect(qs[i].answer,qs[i].originalQNo,m.moduleId,i));navigate('home')})()")
    rec('answering updates goal ring (3 / 20)', '3 / 20' in page.inner_text('.gx-goal') and '17 more' in page.inner_text('.gx-goal'))
    # Seed multi-day history
    page.evaluate(SEED)
    exp = page.evaluate("(()=>{const s=sjStreak();return s})()")
    rec('streak from dated activity (today + 3 previous days = 4)', exp['streak'] == 4, exp)
    rec('calendar has 56 day cells with counts in titles', page.locator('.gx-cal .gx-cell').count() == 56 and 'answered' in page.locator('.gx-cal .gx-cell').first.get_attribute('title'))
    rec('trend line plots last 6 tests', page.locator('.gx-trend .gx-pt').count() == 6)
    page.locator('.gx-trend .gx-pt').nth(5).click(force=True)
    rec('tap on a point shows its details', '80%' in page.inner_text('#gxTrendNote'))
    sub = page.inner_text('.gx-subj')
    rec('subject accuracy from real answers', 'Mathematics' in sub and 'General Science' in sub)
    w = page.evaluate("sjWeekly()")
    rec('weekly card numbers match the engine', str(w['thisW']['a']) in page.inner_text('.gx-week'), w)
    c = page.evaluate("sjCoverage()")
    rec('coverage = unique answered / bank', f"{c['done']} / {c['total']}" in page.inner_text('.gx-cov'), c)
    rec('backup reminder appears once history exists', page.locator('.gx-backup').count() == 1)
    with page.expect_download():
        page.locator('.gx-backup .gx-btn').click()
    page.evaluate("navigate('home')")
    rec('after backup the reminder disappears', page.locator('.gx-backup').count() == 0 and page.evaluate("!!StudySettings.lastBackupAt"))
    t = page.inner_text('#mainView')
    rec('no fabricated numbers', all(x not in t for x in ['78% Avg', '35m / 45m', '8d 🔥']))
    page.screenshot(path=OUT + '/u4c_test_home.png')

    # Pomodoro
    page.locator('.gx-pomo .gx-mini', has_text='15m').click()
    rec('focus length change (15:00)', page.inner_text('#gxPomoTime') == '15:00')
    page.locator('#gxPomoBtn').click()
    page.wait_for_timeout(2300)
    tm = page.inner_text('#gxPomoTime')
    rec('timer counts down live', tm in ('14:58', '14:57', '14:59') and page.evaluate("StudySettings.pomoState.running"), tm)
    page.locator('#gxPomoBtn').click()
    rec('pause keeps remaining time', not page.evaluate("StudySettings.pomoState.running") and page.inner_text('#gxPomoBtn') == 'Resume')
    page.locator('#gxPomoBtn').click()
    before = page.evaluate("Number(StudySettings.focusLog[sjLocalDay()])||0")
    page.evaluate("StudySettings.pomoState.endAt=Date.now()-10; pomoTick()")
    after = page.evaluate("Number(StudySettings.focusLog[sjLocalDay()])||0")
    rec('completed focus session adds 15 min to focus time', after - before == 900, (before, after))
    rec('then switches to break', page.evaluate("StudySettings.pomoState.phase") == 'break' and page.inner_text('#gxPomoTime') == '05:00')
    page.locator('#gxPomoBtn').click()
    page.wait_for_timeout(500)
    page.evaluate("navigate('subjects')"); page.wait_for_timeout(1200); page.evaluate("navigate('home')")
    rec('timer keeps running on other pages', page.evaluate("StudySettings.pomoState.running") and page.inner_text('#gxPomoTime') < '05:00')
    page.wait_for_timeout(500); page.reload(); page.wait_for_selector('.sj-dash', timeout=15000)
    rec('reload: timer state + focus log persisted', page.evaluate("StudySettings.pomoState.running && (Number(StudySettings.focusLog[sjLocalDay()])||0)>=900"))
    page.locator('.gx-pomo .gx-btn.ghost', has_text='Reset').click()
    page.locator('#gxPomoBtn').click(); page.locator('#gxPomoBtn').click()
    page.evaluate("pomoReset()")

    # One-tap tests
    page.evaluate(SEED.replace("navigate('home');", "")) if False else None
    page.locator('.gx-attn .gx-btn', has_text='10-Q test').first.click()
    rec('needs-attention 10-Q topic test starts', page.evaluate("ActiveTestSession?.sessionStatus==='ACTIVE' && ActiveTestSession.questions.length===10 && ActiveTestSession.topicTitle.startsWith('Topic test')"))
    page.evaluate("CbtExitGuard.confirmExit(); navigate('home')")
    page.evaluate("sjMiniTest()")
    rec('daily mini test: 10 questions, one exam/year', page.evaluate("ActiveTestSession?.questions.length===10 && ActiveTestSession.topicTitle==='Daily mini test'"))
    page.evaluate("CbtExitGuard.confirmExit(); navigate('home')")
    page.locator('.gx-rev .gx-btn').click()
    rec('revision widget starts a revision session', page.evaluate("Route.page==='revision_hub' && !!RevisionSession"))
    page.evaluate("revisionEnd(); navigate('home')")
    page.locator('.gx-next .gx-btn').click()
    rec('next best action button works', page.evaluate("Route.page") != 'home' or page.evaluate("!!RevisionSession"))
    page.evaluate("RevisionSession=null; closeModal(); navigate('home')")

    # Layout, themes
    worst = {}
    for theme in ['light', 'dark']:
        if theme == 'dark': page.evaluate("toggleCbtDark()")
        for wd in [360, 390, 768, 1280]:
            page.set_viewport_size({'width': wd, 'height': 900}); page.evaluate("navigate('home')")
            worst[f'{theme}{wd}'] = page.evaluate("(()=>{const m=document.getElementById('mainView');return Math.max(m.scrollWidth-m.clientWidth,document.documentElement.scrollWidth-document.documentElement.clientWidth)})()")
            page.screenshot(path=OUT + f'/u4c_{theme}_{wd}.png')
    rec('no horizontal overflow, light & dark, 360–1280px', max(worst.values()) <= 1, worst)
    page.set_viewport_size({'width': 390, 'height': 844}); page.evaluate("navigate('home')")
    small = page.evaluate("[...document.querySelectorAll('.gx button')].filter(b=>b.offsetParent&&b.getBoundingClientRect().height<32&&!b.classList.contains('sj-inline-link')).map(b=>b.textContent.trim()).slice(0,6)")
    rec('dashboard tap targets ≥ 32px', not small, small)
    contrast = page.evaluate("""(()=>{const el=document.querySelector('.gx-stats b');const c=getComputedStyle(el).color;return c})()""")
    rec('dark text colour is light (readable on dark glass)', contrast in ('rgb(241, 245, 249)',), contrast)
    page.evaluate("toggleCbtDark()")
    page.evaluate("switchWorkspace('ws-board-cbse-10')")
    rec('Board workspace keeps its own dashboard, no glass', page.evaluate("!!document.querySelector('.board-shell') && !document.body.classList.contains('sj-home-active')"))
    page.evaluate("switchWorkspace('ws-comp-legacy')")
    page.evaluate("confirmResetAppData()"); page.wait_for_selector('.sj-dash', timeout=15000)
    rec('reset clears settings, review state and history', page.evaluate("!StudySettings.dailyGoal && !Object.keys(ReviewState.cards).length && AttemptHistory.length===0"))
    rec('no page/console errors', not errors, errors)
    b.close()
json.dump(results, open(OUT + '/u4c_results.json', 'w'), indent=1, ensure_ascii=False)
print('TOTAL', len(results), 'FAIL', sum(1 for r in results if r[1] == 'FAIL'))
